// 조사 상권(서울>권역>상권)만 자치구와 잇는다. 서울 전체·권역은 자치구 후보가 아니다.
export function districtsForRegion(path: string): string[] {
  const parts = path.split('>');
  if (parts.length !== 3 || parts[0] !== '서울') return [];
  return [...(REGION_DISTRICTS[parts[2]] ?? [])];
}
